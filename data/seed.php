/** The EXAMPLE price book. A real install builds its own catalog at /catalog. */
function seed_catalog(): void
{
    foreach (catalog_seed_rows() as $i => $row) {
        Db::insert('catalog_items', ['sort_order' => $i] + $row);
    }
}

