/**
 * Seeding is layered so a real install starts empty:
 *
 *   seed_core()      what the application cannot run without — the admin login,
 *                    settings, and the default markup tiers. No business data.
 *   seed_catalog()   the EXAMPLE products-and-services price book. Opt-in.
 *   seed_staff()     example dispatch/tech logins. Demo and tests only.
 *   seed_demo_data() example customers and jobs at every stage. Demo/tests only.
 *
 * seed_reference_data() is the everything wrapper the test suite uses: tests
 * need a full, known dataset — real installs do not.
 */
function seed_reference_data(bool $withDemo = true): void
{
    seed_core();
    seed_catalog();
    if ($withDemo) { seed_staff(); seed_demo_data(); }
}

function seed_core(): void
{
    $co   = App::config('company');
    $inst = App::config('install', []);

    foreach ([
        'company_name'    => $co['name'],
        'company_phone'   => $co['phone'],
        'company_email'   => $co['email'],
        'company_address' => 'Portland, OR',
        'tax_rate'        => '0',                     // Oregon has no sales tax
        'labor_rate'      => '125.00',
        'mileage_rate'    => '0.72',
        'estimate_terms'  => 'Customer authorizes the work described above and agrees to pay for the services and parts listed. Final invoice may vary if the scope of work changes.',
        'invoice_terms'   => 'Payment due on receipt. Parts carry the manufacturer warranty stated on their line; labour carries a 30-day workmanship warranty. Labour to replace a part under manufacturer warranty is billed at standard rates after the workmanship warranty has lapsed.',
        'invoice_footer'  => 'Final invoice may vary due to job scope changes.',
        'telnyx_api_key'  => '',
        'telnyx_from'     => '',
        'square_access_token' => '',
        'square_location_id'  => '',
        'square_environment'  => 'sandbox',
        'google_maps_key' => '',
        // Texted links (/sign, /locate, /pay) are built from this. Empty
        // falls back to the request host, which is right almost everywhere;
        // a production config generated by setup.php pins it explicitly.
        'app_base_url'    => (string) ($inst['base_url'] ?? ''),
    ] as $k => $v) {
        Db::insert('settings', ['skey' => $k, 'svalue' => (string) $v]);
    }

    // The one admin login the install seeds, so the application is usable on
    // first boot. Which of the two it is turns on a single question: did the
    // operator configure a real password?
    //
    //   password_hash set   — a REAL admin, from `php data/setup.php`. Seeded
    //                         under the configured name and address, NOT
    //                         flagged, never auto-retired. This is how a
    //                         public server comes up.
    //   password_hash empty — a TEMPORARY login at Rules::SETUP_EMAIL with a
    //                         published password, flagged is_setup. Creating
    //                         a real admin under Admin → Users deactivates it
    //                         (see Rules::retireSetupAdmins). Never deleted.
    //
    // The configured address is deliberately ignored in the temporary case:
    // seeding a real person's login with a known password is how the owner's
    // own account ends up marked disposable.
    $admin = (array) ($inst['admin'] ?? []);
    $hash  = (string) ($admin['password_hash'] ?? '');
    $real  = $hash !== '' && (string) ($admin['email'] ?? '') !== '';
    Db::insert('users', $real ? [
        'role'          => 'ADMIN',
        'first_name'    => (string) ($admin['first_name'] ?? '') !== '' ? (string) $admin['first_name'] : 'Admin',
        'last_name'     => (string) ($admin['last_name'] ?? '')  !== '' ? (string) $admin['last_name']  : 'User',
        'email'         => strtolower(trim((string) $admin['email'])),
        'phone_e164'    => phone_to_e164((string) $co['phone']),
        'password_hash' => $hash,
        'is_active' => 1, 'is_setup' => 0, 'can_accept_jobs' => 1, 'created_at' => now(),
    ] : [
        'role'          => 'ADMIN',
        'first_name'    => 'Setup',
        'last_name'     => 'Admin',
        'email'         => Rules::SETUP_EMAIL,
        'phone_e164'    => phone_to_e164((string) $co['phone']),
        'password_hash' => password_hash('admin123', PASSWORD_DEFAULT),
        'is_active' => 1, 'is_setup' => 1, 'can_accept_jobs' => 1, 'created_at' => now(),
    ]);

    // Parts markup matrix — industry-standard defaults (see Markup::DEFAULTS).
    if ((int) Db::val('SELECT COUNT(*) FROM markup_tiers') === 0) {
        $i = 0;
        foreach (Markup::DEFAULTS as [$min, $max, $pct]) {
            Db::insert('markup_tiers', [
                'min_cost'   => number_format($min, 2, '.', ''),
                'max_cost'   => $max === null ? null : number_format($max, 2, '.', ''),
                'markup_pct' => number_format($pct, 2, '.', ''),
                'sort_order' => $i++,
            ]);
        }
    }
}

